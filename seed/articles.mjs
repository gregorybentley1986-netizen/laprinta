const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const cap = (c) => (c ? `<figcaption>${esc(c)}</figcaption>` : "");

export const figure = (src, alt, caption, w, h) =>
  `<figure data-type="image" class="article-figure"><img src="${src}" alt="${esc(alt)}"${w ? ` width="${w}" height="${h}"` : ""}>${cap(caption)}</figure>`;
export const gallery = (imgs, caption) =>
  `<figure data-type="gallery" class="article-gallery"><div class="article-gallery__grid">${imgs
    .map((i) => `<img src="${i.src}" alt="${esc(i.alt)}"${i.w ? ` width="${i.w}" height="${i.h}"` : ""}>`)
    .join("")}</div>${cap(caption)}</figure>`;
export const video = (src, poster, caption) =>
  `<figure data-type="video" class="article-video"><video src="${src}" poster="${poster}" controls="" preload="metadata" playsinline=""></video>${cap(caption)}</figure>`;
export const model = (src, caption) =>
  `<figure data-type="model" class="article-model"><model-viewer src="${src}" alt="${esc(caption)}" camera-controls="" auto-rotate=""></model-viewer>${cap(caption)}</figure>`;
const table = (head, rows) =>
  `<table><tbody><tr>${head.map((h) => `<th><p>${h}</p></th>`).join("")}</tr>${rows
    .map((r) => `<tr>${r.map((c) => `<td><p>${c}</p></td>`).join("")}</tr>`)
    .join("")}</tbody></table>`;

